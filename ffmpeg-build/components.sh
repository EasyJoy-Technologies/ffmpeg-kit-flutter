#!/usr/bin/env bash
# NiceNote FFmpeg component list — the ONLY place that decides what gets compiled, shared by
# Android, iOS, macOS and Windows. Sourced by the build scripts; see ffmpeg-build/README.md.
#
#   nicenote_component_flags [extra-protocol...]   configure flags to append to the upstream line
#   nicenote_verify_components <config_components.h> [extra-protocol...]
#                                                   exact check of what configure really enabled
#
# FFmpeg's configure silently ignores unknown component names, so the verify step is mandatory.

_nn_here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Every audio decoder the pinned source can build (generated by gen_audio_decoders.sh, never edited).
NN_AUDIO_DECODERS="$(paste -sd, "${_nn_here}/audio_decoders.txt")"

# Outputs NiceNote writes: m4a (AAC/ALAC), wav/w64/aiff/caf/flac and raw PCM. mp3 is encoded by the
# app's own LAME, not by ffmpeg.
NN_ENCODERS="aac,alac,flac,pcm_alaw,pcm_mulaw,pcm_u8,pcm_s16le,pcm_s16be,pcm_s24le,pcm_s24be,pcm_s32le,pcm_s32be,pcm_f32le,pcm_f32be,pcm_f64le"
NN_MUXERS="adts,aiff,caf,flac,ipod,mov,mp4,null,wav,w64,matroska_audio,pcm_s16le,pcm_s16be,pcm_s24le,pcm_s32le,pcm_f32le,pcm_f32be,pcm_f64le,pcm_u8,pcm_alaw,pcm_mulaw"

# Filters the ffmpeg command line references by name, the converters libavfilter inserts on its own,
# and a small set of common audio filters kept for later use. (abuffer/abuffersink/buffer/buffersink
# are always built.)
NN_FILTERS="aformat,format,anull,null,atrim,trim,apad,crop,hflip,vflip,transpose,rotate,scale,fps,aresample,\
volume,volumedetect,loudnorm,atempo,afade,amix,amerge,pan,channelmap,channelsplit,join,silenceremove,silencedetect,astats,ebur128,\
highpass,lowpass,acompressor,dynaudnorm,asetpts,asetrate,asplit,anullsrc,concat,aevalsrc,asetnsamples,ashowinfo"

NN_BSFS="aac_adtstoasc,chomp,dca_core,dump_extradata,eac3_core,noise,null,opus_metadata,pcm_rechunk,setts,truehd_core"

# Local files only. Platform-specific protocols (Android: saf) are passed as arguments.
NN_PROTOCOLS="file,pipe,fd"

# All demuxers are built except those that open *other* files by reference (playlists, concat
# lists, image sequences). Video containers stay: m4a/mp4, mka/mkv, wma/wmv share one demuxer.
NN_REF_DEMUXERS="hls,concat,webm_dash_manifest,image2,image2_alias_pix,image2_brender_pix"

# --- what configure turns on or off by itself (checked exactly by nicenote_verify_components) ---
# Pulled in by the dependencies of whitelisted components:
NN_AUTO_MUXERS="matroska"
NN_AUTO_BSFS="av1_frame_merge,evc_frame_merge,pgs_frame_merge,vp9_superframe"
# Demuxers configure cannot build here: need the network (disabled), libxml2 or another library we do not build:
NN_UNAVAILABLE_DEMUXERS="dash,imf,rtp,rtsp,sap,sdp,avisynth,dvdvideo,libgme,libmodplug,libopenmpt,vapoursynth"
NN_UNAVAILABLE_PARSERS="ahx"

nicenote_component_flags() {
  local protocols="$NN_PROTOCOLS" p
  for p in "$@"; do protocols+=",$p"; done
  echo "--disable-everything --disable-network \
--enable-decoder=${NN_AUDIO_DECODERS} \
--enable-encoder=${NN_ENCODERS} \
--enable-demuxers --disable-demuxer=${NN_REF_DEMUXERS} \
--enable-muxer=${NN_MUXERS} \
--enable-parsers \
--enable-bsf=${NN_BSFS} \
--enable-filter=${NN_FILTERS} \
--enable-protocol=${protocols}"
}

# Prints the lower-case names of components of <kind> that are 1 (or 0) in <config_components.h>.
_nn_components() {
  local file=$1 kind=$2 value=$3
  sed -nE "s/^#define CONFIG_([A-Z0-9_]+)_${kind} ${value}\$/\\1/p" "$file" | tr 'A-Z' 'a-z' | LC_ALL=C sort
}

_nn_sorted() { tr ',' '\n' <<< "$1" | grep -v '^$' | LC_ALL=C sort -u; }

# Compares one set; prints differences and returns 1 when they are not identical.
_nn_expect() {
  local label=$1 actual=$2 expected=$3 missing extra
  missing=$(LC_ALL=C comm -13 <(echo "$actual") <(echo "$expected"))
  extra=$(LC_ALL=C comm -23 <(echo "$actual") <(echo "$expected"))
  [[ -z $missing && -z $extra ]] && return 0
  [[ -n $missing ]] && echo "  $label missing: $(echo $missing)"
  [[ -n $extra ]] && echo "  $label unexpected: $(echo $extra)"
  return 1
}

nicenote_verify_components() {
  local C=$1; shift
  local protocols="$NN_PROTOCOLS" p bad=0
  for p in "$@"; do protocols+=",$p"; done
  [[ -f $C ]] || { echo "verify: $C not found"; return 1; }
  _nn_expect decoders "$(_nn_components "$C" DECODER 1)" "$(_nn_sorted "$NN_AUDIO_DECODERS")" || bad=1
  _nn_expect encoders "$(_nn_components "$C" ENCODER 1)" "$(_nn_sorted "$NN_ENCODERS")" || bad=1
  _nn_expect muxers "$(_nn_components "$C" MUXER 1)" "$(_nn_sorted "$NN_MUXERS,$NN_AUTO_MUXERS")" || bad=1
  _nn_expect filters "$(_nn_components "$C" FILTER 1)" "$(_nn_sorted "$NN_FILTERS")" || bad=1
  _nn_expect bsfs "$(_nn_components "$C" BSF 1)" "$(_nn_sorted "$NN_BSFS,$NN_AUTO_BSFS")" || bad=1
  _nn_expect protocols "$(_nn_components "$C" PROTOCOL 1)" "$(_nn_sorted "$protocols")" || bad=1
  _nn_expect "disabled demuxers" "$(_nn_components "$C" DEMUXER 0)" \
    "$(_nn_sorted "$NN_REF_DEMUXERS,$NN_UNAVAILABLE_DEMUXERS")" || bad=1
  _nn_expect "disabled parsers" "$(_nn_components "$C" PARSER 0)" "$(_nn_sorted "$NN_UNAVAILABLE_PARSERS")" || bad=1
  _nn_expect indevs "$(_nn_components "$C" INDEV 1)" "" || bad=1
  _nn_expect outdevs "$(_nn_components "$C" OUTDEV 1)" "" || bad=1
  _nn_expect hwaccels "$(_nn_components "$C" HWACCEL 1)" "" || bad=1
  if [[ $bad -eq 0 ]]; then
    echo "components OK: $(_nn_components "$C" DECODER 1 | wc -l) decoders, $(_nn_components "$C" DEMUXER 1 | wc -l) demuxers, protocols $(echo $(_nn_components "$C" PROTOCOL 1))"
  fi
  return $bad
}
